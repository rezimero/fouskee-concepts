import { useMemo, useState, type FormEvent } from 'react'
import { Check, Copy, Download, ShieldCheck } from 'lucide-react'
import { useNavigate } from 'react-router-dom'
import { requestErrorMessage } from '../../../lib/errors'
import { authApi } from '../api/authApi'
import { AuthLayout } from '../components/AuthLayout'
import { PasswordField } from '../components/PasswordField'
import { useAuth } from '../hooks/useAuth'

type Step = 'password' | 'scan' | 'recovery'

export function MfaSetupPage() {
  const navigate = useNavigate()
  const { refresh } = useAuth()
  const [step, setStep] = useState<Step>('password')
  const [password, setPassword] = useState('')
  const [qrSvg, setQrSvg] = useState('')
  const [code, setCode] = useState('')
  const [recoveryCodes, setRecoveryCodes] = useState<string[]>([])
  const [acknowledged, setAcknowledged] = useState(false)
  const [error, setError] = useState('')
  const [busy, setBusy] = useState(false)

  const qrSource = useMemo(
    () => (qrSvg ? `data:image/svg+xml,${encodeURIComponent(qrSvg)}` : ''),
    [qrSvg],
  )

  async function run(action: () => Promise<void>, fallback: string) {
    setError('')
    setBusy(true)
    try {
      await action()
    } catch (caught) {
      setError(requestErrorMessage(caught, fallback))
    } finally {
      setBusy(false)
    }
  }

  async function confirmPassword(event: FormEvent) {
    event.preventDefault()
    await run(async () => {
      await authApi.confirmPassword(password)
      await authApi.enableMfa()
      setQrSvg(await authApi.qrCode())
      setStep('scan')
    }, 'Unable to start MFA enrollment.')
  }

  async function confirmCode(event: FormEvent) {
    event.preventDefault()
    await run(async () => {
      await authApi.confirmMfa(code)
      setRecoveryCodes(await authApi.recoveryCodes())
      setStep('recovery')
    }, 'The authenticator code could not be verified.')
  }

  async function finish() {
    if (!acknowledged) return
    await refresh()
    navigate('/', { replace: true })
  }

  function downloadCodes() {
    const blob = new Blob([recoveryCodes.join('\n')], { type: 'text/plain' })
    const url = URL.createObjectURL(blob)
    const anchor = document.createElement('a')
    anchor.href = url
    anchor.download = 'fouskee-recovery-codes.txt'
    anchor.click()
    URL.revokeObjectURL(url)
  }

  return (
    <AuthLayout
      eyebrow="Mandatory account protection"
      title="Secure your Fouskee account"
      description="Multi-factor authentication is required before operational access is granted."
    >
      {error && <div className="alert alert--danger">{error}</div>}
      {step === 'password' && (
        <form className="auth-form" onSubmit={confirmPassword}>
          <p className="step-copy">
            Confirm your password before changing security settings.
          </p>
          <PasswordField value={password} onChange={setPassword} />
          <button className="button button--primary" disabled={busy}>
            <ShieldCheck size={18} />
            {busy ? 'Confirming…' : 'Continue to authenticator setup'}
          </button>
        </form>
      )}
      {step === 'scan' && (
        <form className="auth-form" onSubmit={confirmCode}>
          <div className="qr-frame">
            <img src={qrSource} alt="Authenticator enrollment QR code" />
          </div>
          <p className="step-copy">
            Scan the QR code, then enter the six-digit code generated by your app.
          </p>
          <label className="field">
            <span>Authenticator code</span>
            <input
              className="otp-input"
              inputMode="numeric"
              autoComplete="one-time-code"
              value={code}
              onChange={(event) => setCode(event.target.value)}
              required
              autoFocus
            />
          </label>
          <button className="button button--primary" disabled={busy}>
            <Check size={18} />
            {busy ? 'Verifying…' : 'Confirm authenticator'}
          </button>
        </form>
      )}
      {step === 'recovery' && (
        <div className="auth-form">
          <div className="recovery-grid">
            {recoveryCodes.map((item) => <code key={item}>{item}</code>)}
          </div>
          <div className="button-row">
            <button
              className="button button--secondary"
              type="button"
              onClick={() => void navigator.clipboard.writeText(recoveryCodes.join('\n'))}
            >
              <Copy size={17} /> Copy
            </button>
            <button className="button button--secondary" type="button" onClick={downloadCodes}>
              <Download size={17} /> Download
            </button>
          </div>
          <label className="check-row check-row--boxed">
            <input
              type="checkbox"
              checked={acknowledged}
              onChange={(event) => setAcknowledged(event.target.checked)}
            />
            <span>I have stored these recovery codes in a secure location.</span>
          </label>
          <button
            className="button button--primary"
            type="button"
            disabled={!acknowledged}
            onClick={() => void finish()}
          >
            Finish security setup
          </button>
        </div>
      )}
    </AuthLayout>
  )
}
